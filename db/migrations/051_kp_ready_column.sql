-- 051_kp_ready_column.sql
-- „Готови сме за следващия контент план, щом главната карта стигне В продукция."
--
-- Досега клиентът се считаше за зает, докато НЯКОЯ карта със заглавие „{клиент} КП-…"
-- е някъде на дъската извън Done (kp_bc_check_scope = 'board'). На този префикс
-- отговарят и картите за отделните видеа, затова едно върнато за корекции видео от
-- стар КП блокираше следващия план завинаги (Credissimo: главните КП-10 и КП-11 са в
-- Done, а „Credissimo КП-11 - Видео 1 - …" стоеше в „Към Клиент").
--
-- Новото правило ('ready'): броим САМО главната КП карта и то само докато е в колона
-- ПРЕДИ „В продукция". Стигне ли я — пускаме следващия план веднага, независимо колко
-- дни по-рано е. Виж services/kp-create.js (kpMainTitleRegex, isBlockingColumn).

-- Коя колона значи „планът е приет, мислим следващия". Празно = авто по име („В продукция").
INSERT INTO settings (key, value) VALUES ('kp_bc_ready_column_id', '')
ON CONFLICT (key) DO NOTHING;

-- Превключваме от старото „цялата дъска" към новото правило. 'column' (само колоната
-- за създаване) е нарочен избор и не се пипа.
INSERT INTO settings (key, value) VALUES ('kp_bc_check_scope', 'ready')
ON CONFLICT (key) DO UPDATE SET value = 'ready', updated_at = NOW()
WHERE settings.value = 'board';
