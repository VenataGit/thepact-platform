-- 052_sheet_alerts_ignore.sql
-- Игнорирани акаунти за „Известия от таблица".
--
-- Проблемът: когато някой от екипа влезе и пренареди датите на всички видеа,
-- всеки ред ражда известие и бордът се залива. Смисълът на известията е да
-- виждаме какво прави КЛИЕНТЪТ (одобрение, коментар), а не какво пишем ние.
--
-- Списъкът приема цели имейли (ivan@thepact.bg) и цели домейни (@thepact.bg).
-- По подразбиране мълчим за собствения си домейн — точно случаят, от който
-- дойде оплакването. Празен списък = известия от всички.
--
-- ВАЖНО: Google дава имейла на редактора надеждно само за акаунти от нашия
-- домейн; за външен редактор полето често е празно. Празен имейл НИКОГА не се
-- игнорира — иначе точно клиентските одобрения биха изчезнали.

ALTER TABLE sheet_alert_events ADD COLUMN IF NOT EXISTS ignored BOOLEAN NOT NULL DEFAULT FALSE;

INSERT INTO settings (key, value, updated_at) VALUES
    ('sheet_alerts_ignored', '@thepact.bg', NOW())
ON CONFLICT (key) DO NOTHING;
