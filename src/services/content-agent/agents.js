// ---------- извикване ----------

function extractJson(text) {
  const t = String(text || '').trim().replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/i, '');
  const a = t.indexOf('{');
  const b = t.lastIndexOf('}');
  if (a < 0 || b <= a) throw new Error('агентът не върна JSON');
  return JSON.parse(t.slice(a, b + 1));
}

let modelBroken = false; // ако новият модел не е наличен, минаваме на стария до рестарт

async function callJson({ system, user, effort = 'medium', maxTokens = 16000, usage }) {
  let lastErr;
  for (let attempt = 0; attempt < 2; attempt++) {
    let r;
    try {
      r = await callClaude({
        system, maxTokens, effort,
        model: modelBroken ? FALLBACK_MODEL : MODEL,
        // `user` е текст или масив от content блокове (текст + кадри за анализа на видеата).
        messages: [{ role: 'user', content: !attempt ? user : Array.isArray(user)
          ? [...user, { type: 'text', text: 'ВНИМАНИЕ: предишният ти отговор не беше валиден JSON. Върни САМО JSON обекта.' }]
          : `${user}\n\nВНИМАНИЕ: предишният ти отговор не беше валиден JSON. Върни САМО JSON обекта.` }],
      });
    } catch (e) {
      if (!modelBroken && /model/i.test(e.message) && /(404|not.?found|invalid)/i.test(e.message)) {
        modelBroken = true;
        console.warn(`[content-agent] моделът ${MODEL} не е наличен — минавам на ${FALLBACK_MODEL}`);
        attempt -= 1;
        continue;
      }
      throw e;
    }
    if (usage) {
      usage.input = (usage.input || 0) + (r.usage.input_tokens || 0);
      usage.output = (usage.output || 0) + (r.usage.output_tokens || 0);
      usage.calls = (usage.calls || 0) + 1;
      usage.model = r.model;
    }
    try {
      return extractJson(r.text);
    } catch (e) {
      lastErr = new Error(`${e.message} (stop: ${r.stopReason})`);
    }
  }
  throw lastErr;
}

