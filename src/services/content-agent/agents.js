/**
 * Пуска една стъпка: експерт → проверител → (поправка → проверка)…
 * @returns {{ output: object, reviews: object[] }}
 */
async function runStep(stepKey, ctx, chunk, usage, onProgress) {
  const step = STEPS[stepKey];
  const input = step.input(ctx, chunk);
  let output = await callJson({ system: step.expert.system, user: input, effort: 'medium', usage });
  const reviews = [];
  for (let round = 1; round <= MAX_ROUNDS; round++) {
    const review = await callJson({
      system: step.checker.system,
      user: `${input}\n\n${block('резултат_за_проверка', output)}`,
      effort: 'low', maxTokens: 8000, usage,
    });
    reviews.push(review);
    if (review.ok || round === MAX_ROUNDS || !Array.isArray(review.issues) || !review.issues.length) break;
    if (onProgress) onProgress(`${step.title}: ${step.checker.role} върна ${review.issues.length} забележки — поправка ${round}`);
    output = await callJson({
      system: step.expert.system,
      user: `${input}\n\n${block('твоят_предишен_резултат', output)}\n\n${block('забележки_от_проверителя', review.issues)}\n\nПоправи резултата според забележките. Върни целия поправен JSON в същия формат.`,
      effort: 'medium', usage,
    });
  }
  return { output, reviews };
}

